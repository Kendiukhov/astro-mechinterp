"""
E1b — E1 Part B, redone with a FAITHFUL representation of a detection miss.

Why this exists
---------------
E1 measured the detection-miss rate correctly (3.68% of targets have no segment covering
their centre pixel, over 5000 real cutouts) but PROPAGATED it by zeroing the entire
segmentation field:

    p_missonly = binary.clone(); p_missonly[miss] = 0.0        # e1_incidence_and_impact.py:166

That tensor is bit-identical in construction to the `erased` arm of D2, which that experiment
labels "OFF-MANIFOLD, reported but discounted" — and it is the most damaging of all ten arms
there (median |rel change| 81%). Re-reading the survey masks shows an all-zero field occurs in
0 of 5000 real cutouts: every one of the 184 misses still contains segments elsewhere in the
frame. The pipeline fails to put a segment ON THE TARGET; it does not return a blank image.

So E1's headline number was generated by a perturbation that never actually happens.

What this does instead
----------------------
PART A banks the real segmentation fields of the cutouts that ARE misses. PART B then
represents a miss by TRANSPLANTING one of those real fields — the object keeps its own pixels
but receives a segmentation map drawn from the empirical distribution of what the pipeline
actually outputs when it misses a target.

Everything else is held fixed against E1 on purpose: same seed, same scanned rows, same 960
galaxies, same objects flagged as missed, same displacement draws. The `miss_erased` scenario
reproduces E1's original arm exactly, so the two can be compared as a controlled pair and the
overstatement can be quantified rather than asserted.

Run:  python experiments/e1b_faithful_miss.py [N_SCAN] [N_IMPACT]
Out:  results/e1b_faithful_miss.json
"""

from __future__ import annotations

import json
import pathlib
import sys

import numpy as np
import torch

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))

import astron_mi as A
from astron_mi import physics as P

RESULTS = pathlib.Path(__file__).resolve().parent.parent / "results"
N_SCAN = int(sys.argv[1]) if len(sys.argv) > 1 else 5000
N_IMPACT = int(sys.argv[2]) if len(sys.argv) > 2 else 960
BATCH = 16
DEVICE = "mps" if torch.backends.mps.is_available() else "cpu"
SEED = 0
CROP = 96
N_BOOT = 500
LSST_REQ = 0.003
TOMO_EDGES = [0.0, 0.15, 0.25, 0.35, 1.0]

SCENARIOS = ("miss_erased", "miss_real", "miss_real_shift")
CONFIGS = ("img", "img_spec")


def centre_crop(x, n=CROP):
    h, w = x.shape[-2:]
    r, c = (h - n) // 2, (w - n) // 2
    return x[..., r:r + n, c:c + n]


def boot_ci(v, fn=np.mean, n=N_BOOT, seed=SEED):
    v = np.asarray(v); v = v[np.isfinite(v)]
    if len(v) < 3:
        return float("nan"), float("nan"), float("nan")
    rng = np.random.default_rng(seed)
    st = [fn(v[rng.integers(0, len(v), len(v))]) for _ in range(n)]
    return float(fn(v)), float(np.percentile(st, 16)), float(np.percentile(st, 84))


def central_coverage(binary, k=12):
    """Fraction of the central k x k box that is labelled, on the 96px analysis crop."""
    c = centre_crop(binary)
    h = c.shape[-1] // 2
    return c[..., h - k // 2:h + k // 2, h - k // 2:h + k // 2].mean(dim=(-2, -1))


def main():
    from aion.modalities import LegacySurveySegmentationMap, Z

    rng = np.random.default_rng(SEED)          # mirrors E1's stream exactly
    rng_t = np.random.default_rng(1234)        # transplant draws only; does not perturb the above
    cm = A.load_codecs(DEVICE)
    model = A.load_model("base", device=DEVICE)
    T = P.tables()

    # ------------------------------------------------------------- PART A
    print(f"PART A — scanning {N_SCAN} real cutouts, banking the misses")
    no_centre, offsets, n_seen = 0, [], 0
    miss_bank, det_cov, miss_cov, miss_area, det_area = [], [], [], [], []
    with A.ProvabgsReader() as r:
        rows = np.sort(rng.choice(r.n_rows(), min(N_SCAN, r.n_rows()), replace=False))
        for s in range(0, len(rows), BATCH):
            b = r.aion_batch(rows[s:s + BATCH], with_segmap=True,
                             with_image=False, with_spectrum=False)
            full = b["segmap"]
            binary = (full > 0).float()
            cov = central_coverage(binary)
            seg = centre_crop(full)
            for i in range(len(seg)):
                n_seen += 1
                cid = float(seg[i, CROP // 2, CROP // 2])
                area = float(binary[i].sum())
                if cid <= 0:
                    no_centre += 1
                    miss_bank.append(binary[i].clone())      # a REAL miss field
                    miss_cov.append(float(cov[i])); miss_area.append(area)
                    continue
                det_cov.append(float(cov[i])); det_area.append(area)
                m = (seg[i] == cid)
                yy, xx = torch.nonzero(m, as_tuple=True)
                cy, cx = yy.float().mean().item(), xx.float().mean().item()
                offsets.append(float(np.hypot(cy - (CROP - 1) / 2, cx - (CROP - 1) / 2)))
            if (s // BATCH) % 40 == 0:
                print(f"  {min(s + BATCH, len(rows))}/{len(rows)}", flush=True)

    offsets = np.array(offsets)
    p_miss = no_centre / max(n_seen, 1)
    n_blank = sum(1 for m in miss_bank if float(m.sum()) == 0.0)
    print(f"  scanned {n_seen}; misses {no_centre} ({100 * p_miss:.2f}%)")
    print(f"  of those misses, COMPLETELY BLANK fields: {n_blank}  "
          f"<- E1 assumed this was all of them")
    print(f"  central 12x12 coverage: miss median {np.median(miss_cov):.3f} vs "
          f"detected {np.median(det_cov):.3f}")
    print(f"  labelled area (px):     miss median {np.median(miss_area):.0f} vs "
          f"detected {np.median(det_area):.0f}")

    part_a = {
        "n_scanned": int(n_seen),
        "frac_no_segment_at_centre": float(p_miss),
        "n_misses_banked": int(len(miss_bank)),
        "n_misses_completely_blank": int(n_blank),
        "miss_central_coverage_median": float(np.median(miss_cov)),
        "detected_central_coverage_median": float(np.median(det_cov)),
        "miss_labelled_area_px_median": float(np.median(miss_area)),
        "detected_labelled_area_px_median": float(np.median(det_area)),
        "centroid_offset_px": {
            "median": float(np.median(offsets)), "p90": float(np.percentile(offsets, 90)),
            "p99": float(np.percentile(offsets, 99)),
            "frac_gt_10px": float(np.mean(offsets > 10)),
        },
    }
    bank = torch.stack(miss_bank)
    print(f"  banked {len(bank)} real miss fields")

    # ------------------------------------------------------------- PART B
    print(f"\nPART B — tomographic impact, {N_IMPACT} galaxies, {len(SCENARIOS)} scenarios")

    def seg_tok(binary):
        t = cm.encode(LegacySurveySegmentationMap(field=binary.clone().to(DEVICE)))
        return {k: v.reshape(v.shape[0], -1) for k, v in t.items()}

    def zmedian(tok):
        o = model.forward({k: v.to(DEVICE) for k, v in tok.items()}, target_modality=[Z])
        lg = o["tok_z"][:, 0, :].detach().float().cpu().numpy()
        p = np.exp(lg - lg.max(1, keepdims=True)); p /= p.sum(1, keepdims=True)
        pm = p[:, :1024] / p[:, :1024].sum(1, keepdims=True)
        vals = T.index_to_value("tok_z")
        return vals[np.argmax(np.cumsum(pm, 1) >= 0.5, 1)]

    zt_l = []
    z_true = {c: [] for c in CONFIGS}
    z_pert = {(c, sc): [] for c in CONFIGS for sc in SCENARIOS}
    n_missed_total = 0
    with A.ProvabgsReader() as r:
        rows = np.sort(rng.choice(r.n_rows(), N_IMPACT, replace=False))
        for s in range(0, N_IMPACT, BATCH):
            b = r.aion_batch(rows[s:s + BATCH], with_segmap=True)
            ti = A.encode_image(cm, b["image"]["flux"], b["image"]["bands"], device=DEVICE)
            ts = A.encode_spectrum(cm, **b["spectrum"], survey="desi", device=DEVICE)
            binary = (b["segmap"] > 0).float()

            # --- identical rng consumption to E1, so the SAME objects are flagged missed
            miss = rng.random(len(binary)) < p_miss
            n_missed_total += int(miss.sum())
            p_erased = binary.clone(); p_erased[miss] = 0.0
            p_real = binary.clone()
            p_real_shift = binary.clone()
            shifts = []
            for i in range(len(binary)):
                if miss[i]:
                    shifts.append(None)
                else:
                    shifts.append(int(round(float(rng.choice(offsets)))))
            # --- the only change: a miss gets a REAL miss field, not a blank one
            for i in range(len(binary)):
                if miss[i]:
                    j = int(rng_t.integers(0, len(bank)))
                    p_real[i] = bank[j]
                    p_real_shift[i] = bank[j]
                elif shifts[i]:
                    p_real_shift[i] = torch.roll(p_real_shift[i], shifts=(shifts[i], 0),
                                                 dims=(-2, -1))
            perts = {"miss_erased": p_erased, "miss_real": p_real,
                     "miss_real_shift": p_real_shift}

            zt_l.append(np.asarray(b["labels"]["z"], dtype="float64"))
            bases = {"img": dict(ti), "img_spec": {**ti, **ts}}
            st = seg_tok(binary)
            stok = {sc: seg_tok(perts[sc]) for sc in SCENARIOS}
            for c in CONFIGS:
                z_true[c].append(zmedian({**bases[c], **st}))
                for sc in SCENARIOS:
                    z_pert[(c, sc)].append(zmedian({**bases[c], **stok[sc]}))
            print(f"  {min(s + BATCH, N_IMPACT)}/{N_IMPACT}", flush=True)

    zt_all = np.concatenate(zt_l)
    ok = np.isfinite(zt_all)
    zt = zt_all[ok]
    by_config = {}
    for c in CONFIGS:
        for sc in SCENARIOS:
            z0 = np.concatenate(z_true[c])[ok]
            z1 = np.concatenate(z_pert[(c, sc)])[ok]
            bins, worst = [], 0.0
            for lo, hi in zip(TOMO_EDGES[:-1], TOMO_EDGES[1:]):
                m = (zt >= lo) & (zt < hi)
                if m.sum() < 10:
                    continue
                mt, mp = float(z0[m].mean()), float(z1[m].mean())
                zc = 0.5 * (lo + hi)
                shift = abs(mp - mt) / (1 + zc)
                d, dlo, dhi = boot_ci(z1[m] - z0[m])
                worst = max(worst, shift)
                bins.append({"lo": lo, "hi": hi, "n": int(m.sum()),
                             "mean_true": mt, "mean_perturbed": mp,
                             "shift_over_1pz": shift, "delta_ci": [d, dlo, dhi],
                             "exceeds_requirement": bool(shift > LSST_REQ)})
            by_config[f"{c}|{sc}"] = {
                "bins": bins, "worst_shift": worst,
                "worst_over_requirement": worst / LSST_REQ,
                "n_bins_exceeding": sum(b["exceeds_requirement"] for b in bins),
            }
            print(f"  {c:9s} {sc:16s} worst {worst:.5f} = {worst / LSST_REQ:5.2f}x req, "
                  f"{by_config[f'{c}|{sc}']['n_bins_exceeding']}/{len(bins)} bins exceed")

    e = by_config["img|miss_erased"]["worst_over_requirement"]
    f = by_config["img|miss_real"]["worst_over_requirement"]
    out = {
        "n_impact": int(N_IMPACT), "n_flagged_missed": int(n_missed_total),
        "part_a": part_a, "part_b": {"by_config": by_config},
        "comparison": {
            "erased_worst_over_req": e, "faithful_worst_over_req": f,
            "overstatement_factor": (e / f) if f > 0 else None,
        },
        "verdict": ("E1's all-zero miss field overstates the tomographic bias by "
                    f"{e / f:.2f}x relative to transplanting a real miss field"
                    if f > 0 else "faithful arm gives zero bias"),
    }
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "e1b_faithful_miss.json").write_text(json.dumps(out, indent=1))
    print("\n" + out["verdict"])
    print("wrote results/e1b_faithful_miss.json")


if __name__ == "__main__":
    main()
