#!/usr/bin/env python3
"""
Build the TMLR submission version from paper/main.tex.

main.tex is the working manuscript: standalone `article`, named author block, appendices before
the bibliography. TMLR needs a different shape -- its own style file, a one-paragraph abstract,
an anonymised author block, a Broader Impact Statement, and appendices AFTER the bibliography.
Rather than maintain two divergent manuscripts, this script derives the submission version from
the working one, so a correction to the science only ever has to be made once.

What is NOT inherited from main.tex, and lives here instead:
  * the preamble (tmlr.sty already loads natbib and fancyhdr; loading them again breaks it)
  * the abstract (TMLR requires exactly one paragraph; main.tex's runs to four)
  * the title (submission leads with the transferable claim, not the case study)
  * the Broader Impact Statement (TMLR-specific section)
  * the Acknowledgements, which are dropped entirely: they would de-anonymise the submission.

Run:  python paper/make_submission.py && cd paper/submission && pdflatex main && bibtex main && pdflatex main && pdflatex main
"""

import pathlib
import shutil

HERE = pathlib.Path(__file__).resolve().parent
SUB = HERE / "submission"

PREAMBLE = r"""% Generated by make_submission.py from ../main.tex -- do not edit directly.
\documentclass[10pt]{article}
\usepackage{tmlr}

\usepackage{graphicx}
\usepackage{booktabs}
\usepackage{amsmath,amssymb}
\usepackage{float}
\usepackage{caption}
\usepackage{subcaption}
\usepackage{xcolor}
\usepackage{siunitx}
\usepackage{microtype}
\usepackage{url}

\captionsetup{font=small,labelfont=bf}
\sisetup{detect-all}

\newcommand{\aion}{AION-1}
\newcommand{\dmag}{|\Delta\mathrm{mag}|}
\newcommand{\dzreq}{|\Delta\langle z\rangle|/(1+z)}

\title{Foundation models defer to their metadata channel:\\
a causal audit of \aion{}}

\author{\name Anonymous \email anonymous@example.com \\
      \addr Anonymous Institution}

\begin{document}
\maketitle
"""

ABSTRACT = r"""\begin{abstract}
Multimodal scientific foundation models are increasingly trained on raw observations alongside
catalogue-derived products computed from them. We show, for \aion{}---a 40-table transformer
foundation model for astronomy trained on more than $2\times10^{8}$ objects and released with
open weights \citep{parker2025aion}---that this design choice creates a systematic failure:
the model defers to the catalogue channel over the pixels, and does not discount it when the two
conflict. Holding image tokens byte-identical and editing only the survey segmentation map moves
every quantity the model reports---flux, size, ellipticity, redshift---by 110--4400 times a
matched placebo; corrupting catalogue photometry instead leaves the model nine times worse than
supplying no metadata at all. Causal interventions identify the mechanism as detection
\emph{gating}, presence at the field centre ($r=0.47$) rather than the light the mask encloses
($r=0.30$), and across 322 real blended systems the model ignores entirely how the pipeline
partitioned the light ($R=-0.006$). We price the consequence: propagating the survey's own
measured 3.68\,\% detection-miss rate, represented by the segmentation fields the pipeline
actually returns when it misses, shifts tomographic mean redshifts by a median 0.71 times the
LSST DESC requirement over 40 miss assignments and exceeds it in 12 of them, unchanged when the
missed objects are drawn by their measured magnitude-dependent miss probability rather than
uniformly; observed positional errors take the worst bin to 8.3 times. Withholding the detection channel removes the
vulnerability at no measurable cost, and the effect grows with model scale. Two further limits
are in the tokeniser, not the transformer: the image codec resolves 28 effective states on
source patches against 934 for the spectrum codec, and the redshift readout is
quantisation-limited. Finally, sparse dictionaries are unreliable as causal handles
on this target: across 15 dictionaries spanning width, sparsity and seed, recovery of the gated
readout spans 26--75\,\% and moves by up to 18 points on the seed alone, thirteen of fifteen
lose to difference-in-means, and reconstruction quality does not predict which dictionary will
steer.
\end{abstract}
"""

BROADER = r"""
\subsubsection*{Broader Impact Statement}
This paper identifies a failure mode in a released scientific foundation model that is silent:
a wrong detection map produces a confident wrong answer rather than a widened posterior. The
intended impact is defensive---we quantify the resulting bias, show it is invisible in the
model's output, and give a mitigation (withhold the detection channel when it cannot be vouched
for) that costs nothing measurable. The main risk of publication is that the audited numbers are
read as a general verdict on the model or on multimodal scientific pretraining. Their scope is
narrower: all measurements are on one model family, one survey and one depth, and
\S\ref{sec:impact} states the assumptions behind the cosmological figure explicitly. The
software issues in Appendix~\ref{app:bugs} are engineering notes against a pinned release, and
we note that this audit was possible only because the authors released weights, code and
tokenisers openly.
"""


def slice_between(body, start, end):
    i = body.find(start)
    j = body.find(end)
    if i < 0 or j < 0:
        raise SystemExit(f"marker not found: {start!r} / {end!r}")
    return body[i + len(start):j]


def main():
    src = (HERE / "main.tex").read_text()
    body = slice_between(src, "\\begin{document}", "\\end{document}")

    main_body = slice_between(body, "\\end{abstract}", "\\appendix")
    appendices = slice_between(body, "\\appendix", "\\section*{Data and code availability}")
    datacode = slice_between(body, "\\section*{Data and code availability}",
                             "\\section*{Acknowledgements}")

    out = (PREAMBLE + ABSTRACT + main_body + BROADER
           + "\n\\subsubsection*{Data and Code Availability}\n" + datacode
           + "\n\\bibliography{refs}\n\\bibliographystyle{tmlr}\n\n\\appendix\n" + appendices
           + "\n\\end{document}\n")

    SUB.mkdir(exist_ok=True)
    (SUB / "main.tex").write_text(out)
    shutil.copy(HERE / "refs.bib", SUB / "refs.bib")
    if (HERE / "figs").is_dir():
        shutil.copytree(HERE / "figs", SUB / "figs", dirs_exist_ok=True)
    for sty in ("tmlr.sty", "tmlr.bst", "fancyhdr.sty"):
        s = HERE / "tmlr" / sty
        if s.exists():
            shutil.copy(s, SUB / sty)

    leaks = [w for w in ("Author list to be completed", "Affiliation to be completed",
                         "Acknowledgement", "requires a domain co-author")
             if w.lower() in out.lower()]
    print(f"wrote {SUB/'main.tex'} ({len(out)} chars)")
    print("anonymity check:", "LEAK -> " + ", ".join(leaks) if leaks else "clean")


if __name__ == "__main__":
    main()
